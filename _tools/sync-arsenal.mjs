// Copies the guns and their recipes into the server's shared folder (edge functions cannot import from src/):
//   node _tools/sync-arsenal.mjs     ->  supabase/functions/_shared/arsenal.ts
import fs from 'node:fs';
let s = fs.readFileSync('src/lib/raid/weapons.ts', 'utf8').replace(/\r\n/g, '\n');
s = s.replace("import type { LootBag } from './loot';", "type LootBag = Partial<Record<string, number>>;");
s = '// GENERATED by _tools/sync-arsenal.mjs from src/lib/raid/weapons.ts: do not edit here.\n' + s;
fs.writeFileSync('supabase/functions/_shared/arsenal.ts', s);
console.log('written');
