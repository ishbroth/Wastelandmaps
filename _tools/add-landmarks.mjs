// Puts the renders made by gen-batch.mjs into the app: copies the pictures to public/renders and writes src/lib/rendersMore.ts.
//   node _tools/add-landmarks.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const DIR = path.join(ROOT, '_data', 'gen2');
const POST_NAMES = { fandf: 'Revolution Tower' }; // what the wasteland calls it, where that is not simply its real name
const entries = [];
for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith('-meta.json')).sort()) {
  const slug = file.replace('-meta.json', '');
  if (!fs.existsSync(path.join(DIR, `${slug}-fallout.png`))) continue;
  const meta = JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8'));
  fs.copyFileSync(path.join(DIR, `${slug}-fallout.png`), path.join(ROOT, 'public', 'renders', `${meta.id}.png`));
  fs.copyFileSync(path.join(DIR, `${slug}-source.jpg`), path.join(ROOT, 'public', 'renders', `${meta.id}-source.jpg`));
  const q = (s) => JSON.stringify(s ?? '');
  entries.push(`  ${meta.id}: { name: ${q(meta.label)}, photo: ${q(meta.file.replace(/\.[a-z]+$/i, ''))}, author: ${q(meta.author)}, license: ${q(meta.license)}, page: ${q(meta.page)}, lat: ${meta.lat}, lng: ${meta.lng}${POST_NAMES[slug] ? `, postName: ${q(POST_NAMES[slug])}` : ''} },`);
}
fs.writeFileSync(path.join(ROOT, 'src', 'lib', 'rendersMore.ts'), `// Generated by _tools/add-landmarks.mjs: more landmarks with a snapshot that everyone can see. Each stands at lat/lng, and always shows on the map
// of its metro. The first seven are in renders.ts.
import type { FreeRender } from './renders';

export const MORE_RENDERS: Record<string, FreeRender> = {
${entries.join('\n')}
};
`);
console.log(entries.length, 'landmarks added');
