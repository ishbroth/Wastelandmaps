// Copies the home vault's rules into the server's shared folder (edge functions cannot import from src/):
//   node _tools/sync-vault.mjs     ->  supabase/functions/_shared/vaultHome.ts
import fs from 'node:fs';
let s = fs.readFileSync('src/lib/vaultHome.ts', 'utf8').replace(/\r\n/g, '\n');
s = '// GENERATED by _tools/sync-vault.mjs from src/lib/vaultHome.ts: do not edit here.\n' + s;
fs.writeFileSync('supabase/functions/_shared/vaultHome.ts', s);
console.log('written');
