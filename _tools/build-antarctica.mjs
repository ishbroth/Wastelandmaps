// Writes supabase/functions/_shared/antarctica.ts: a simplified outline of Antarctica (Natural Earth, public domain) and the test the app and the
// server both use to decide whether a GPS position is in Antarctica (for the discovery of Vault 0, Vault Tech Headquarters).
//   node _tools/build-antarctica.mjs
// Needs, in _data/: ne_10m_land.geojson (already there for the metro tools) and the ice shelves (McMurdo, Halley and the like stand on them):
//   curl -L -o _data/ne_10m_antarctic_ice_shelves_polys.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_antarctic_ice_shelves_polys.geojson
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, '_data', f), 'utf8'));
const polysOf = (g) => g.features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates));
// the land entirely south of 60.5 S (the continent, its islands), plus every ice shelf
const polys = [...polysOf(read('ne_10m_land.geojson')).filter((p) => Math.max(...p[0].map((c) => c[1])) < -60.5), ...polysOf(read('ne_10m_antarctic_ice_shelves_polys.geojson'))];

/** Douglas-Peucker, in degrees (fine this close to the coast; the test adds a margin of its own). */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const [a, b] = [points[0], points.at(-1)];
  let worst = -1, at = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [x, y] = points[i];
    const dx = b[0] - a[0], dy = b[1] - a[1];
    const t = dx || dy ? Math.max(0, Math.min(1, ((x - a[0]) * dx + (y - a[1]) * dy) / (dx * dx + dy * dy))) : 0;
    const d = Math.hypot(x - (a[0] + t * dx), y - (a[1] + t * dy));
    if (d > worst) { worst = d; at = i; }
  }
  return worst > tolerance ? [...simplify(points.slice(0, at + 1), tolerance).slice(0, -1), ...simplify(points.slice(at), tolerance)] : [a, b];
}
const round = (n) => Math.round(n * 20) / 20;
const rings = polys.map((p) => simplify(p[0], 0.2).flatMap(([x, y]) => [round(x), round(y)]));
const points = rings.reduce((n, r) => n + r.length / 2, 0);

const out = `// Antarctica, for Vault 0 (Vault Tech Headquarters): a simplified outline and the test for "is this position in Antarctica". Shared by the app and by the
// server functions, so both decide the same way. GENERATED by _tools/build-antarctica.mjs from Natural Earth (public domain): do not edit by hand.

/** Outer rings of the continent and its islands and ice shelves, each a flat [lng, lat, lng, lat, ...] list. */
export const ANTARCTICA_RINGS: number[][] = ${JSON.stringify(rings)};

/** The South Shetland Islands (King George Island and its research stations), just off the tip of the Peninsula. */
const SOUTH_SHETLANDS = { south: -63.9, north: -61.8, west: -63.5, east: -53.5 };

/** How far outside the coarse outline still counts (the outline is simplified, and coasts and ice shelves move). */
const MARGIN_KM = 30;

function inside(ring: number[], lat: number, lng: number): boolean {
  let hit = false;
  for (let i = 0, j = ring.length - 2; i < ring.length; j = i, i += 2) {
    const [xi, yi, xj, yj] = [ring[i], ring[i + 1], ring[j], ring[j + 1]];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

/** Kilometres from the point to the nearest edge of the ring (flat approximation, good for the short distances the margin needs). */
function edgeKm(ring: number[], lat: number, lng: number): number {
  const kx = 111.32 * Math.max(0.05, Math.cos((lat * Math.PI) / 180));
  const ky = 111.32;
  let best = Infinity;
  for (let i = 0; i < ring.length - 2; i += 2) {
    const [x1, y1, x2, y2] = [ring[i], ring[i + 1], ring[i + 2], ring[i + 3]];
    if ((y1 <= -89.9 && y2 <= -89.9) || (Math.abs(x1) === 180 && Math.abs(x2) === 180 && x1 === x2)) continue; // the closing lines along the pole and the date line are not coast
    const wrap = (d: number) => ((((d + 180) % 360) + 360) % 360) - 180;
    const ax = wrap(x1 - lng) * kx, ay = (y1 - lat) * ky;
    const bx = ax + wrap(x2 - x1) * kx, by = (y2 - lat) * ky;
    const dx = bx - ax, dy = by - ay;
    const t = dx || dy ? Math.max(0, Math.min(1, -(ax * dx + ay * dy) / (dx * dx + dy * dy))) : 0;
    best = Math.min(best, Math.hypot(ax + t * dx, ay + t * dy));
  }
  return best;
}

/** Is this position in Antarctica: on the continent, an island or ice shelf of it, or within a few kilometres of its coast? Not the Southern Ocean off South America, nor ships crossing the Drake Passage. */
export function inAntarctica(lat: number, lng: number): boolean {
  if (!Number.isFinite(lat) || !Number.isFinite(lng) || lat > -61.7) return false;
  const x = ((((lng + 180) % 360) + 360) % 360) - 180;
  const s = SOUTH_SHETLANDS;
  if (lat >= s.south && lat <= s.north && x >= s.west && x <= s.east) return true;
  if (ANTARCTICA_RINGS.some((r) => inside(r, lat, x))) return true;
  return lat < -62.5 && ANTARCTICA_RINGS.some((r) => edgeKm(r, lat, x) <= MARGIN_KM);
}
`;
fs.writeFileSync(path.join(ROOT, 'supabase', 'functions', '_shared', 'antarctica.ts'), out);
console.log(`antarctica.ts: ${rings.length} rings, ${points} points, ${(out.length / 1024).toFixed(1)} KB`);
